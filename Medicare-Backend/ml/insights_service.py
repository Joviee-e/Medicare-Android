"""
Predictive Intelligence Insights Service
Aggregates the 3 ML components (Adherence Prediction, Routine Analysis, Smart Reminder Optimization)
and provides secure recommendation acceptance.
"""

import os
import json
import logging
from bson import ObjectId
from models.medicine import MedicineModel
from database.mongo import get_medicines_collection
from ml.adherence_predictor import predict_adherence
from ml.routine_analyzer import analyze_routine
from ml.reminder_optimizer import optimize_reminders

logger = logging.getLogger(__name__)


def get_patient_predictive_insights(patient_id: str) -> dict:
    """
    Retrieves all medicines and logs for a patient and evaluates:
    1. Medication Adherence Prediction (Random Forest)
    2. Medication Routine Analysis (K-Means)
    3. Smart Reminder Optimization (Regression & Delay Analytics)
    """
    medicines = MedicineModel.get_by_patient(patient_id)

    adherence_result = predict_adherence(medicines)
    routine_result = analyze_routine(medicines)
    reminder_result = optimize_reminders(medicines)

    # Determine overall data status
    total_logs = adherence_result.get("total_logged_doses", 0)
    if total_logs < 5:
        overall_status = "insufficient_data"
    else:
        overall_status = "ready"

    return {
        "status": overall_status,
        "patient_id": patient_id,
        "total_active_medications": len(medicines),
        "total_logged_doses": total_logs,
        "adherence": adherence_result,
        "routine": routine_result,
        "reminder_optimization": reminder_result,
        "disclaimer": "Predictive insights are generated by machine learning models using historical intake telemetry to support adherence. They do not substitute professional medical advice."
    }


def apply_reminder_suggestion(patient_id: str, medicine_id: str, current_time: str, suggested_time: str, confirmed: bool) -> tuple:
    """
    Safely applies a recommended reminder time adjustment after explicit user confirmation.
    SAFETY RULES:
    - Never modifies medicine name, dosage, or dosing frequency.
    - Only updates the notification reminder_time.
    - Must be confirmed by user.
    """
    if not confirmed:
        return False, "User confirmation is strictly required to adjust reminder timings."

    if not medicine_id or not current_time or not suggested_time:
        return False, "Missing medicine_id, current_time, or suggested_time."

    medicines_col = get_medicines_collection()
    try:
        med_doc = medicines_col.find_one({"_id": ObjectId(medicine_id), "patient_id": ObjectId(patient_id)})
        if not med_doc:
            return False, "Medication not found or access denied."

        current_reminders = med_doc.get("reminder_times", [])
        if current_time not in current_reminders:
            return False, f"Current reminder time '{current_time}' not found in active schedule."

        # Replace reminder time
        new_reminders = [suggested_time if t == current_time else t for t in current_reminders]

        medicines_col.update_one(
            {"_id": ObjectId(medicine_id), "patient_id": ObjectId(patient_id)},
            {"$set": {"reminder_times": new_reminders}}
        )

        return True, f"Reminder time successfully updated from {current_time} to {suggested_time} for {med_doc.get('name')}."
    except Exception as e:
        logger.error(f"Error updating reminder time: {e}", exc_info=True)
        return False, str(e)

